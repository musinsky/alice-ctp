#!/usr/bin/env bash

# 2026-07-16

ts_human_to_millis() {
  # "2026-07-15 21:47:52.718+02:00" => 1784144872718
  local ts="$1"
  date --date="${ts}" +%s%3N
}
ts_millis_to_human() {
  # 1784144872718 => "2026-07-15 21:47:52.718+02:00"
  local ts="$1"
  date --date="@${ts:0:-3}.${ts: -3}" "${DATE_FMT}"
  #                        ${ts: -3}=${ts:${#ts}-3}=${ts:13-3}
}
ts_human_format() {
  # 2026-06-30 (or any other format) => "2026-06-30 00:00:00.000+02:00"
  local ts="$1"
  if [[ "${ts}" == "0" ]]; then # special case for timestamp '1970-01-01'
    date --date="@0" "${DATE_FMT}"
  else
    date --date="${ts}" "${DATE_FMT}"
  fi
}
uuid_time() {
  # 776b570c-71d4-11f1-b15c-0aa202c71b9a => "2026-06-27 05:01:17,572481+02:00"
  local uuid="$1"
  uuidparse --noheadings --output TIME "${uuid}"
}
curl_ccdb() {
  local ts_lower_millis
  local ts_upper_millis
  ts_lower_millis="$(ts_human_to_millis "${TS_LOWER}")"
  ts_upper_millis="$(ts_human_to_millis "${TS_UPPER}")"
  local curl_headers=(
    --header "Accept: application/json"          # default 'text/plain'
    --header "If-Not-Before: ${ts_lower_millis}" # creation timestamp >=
    --header "If-Not-After: ${ts_upper_millis}"  # creation timestamp <=
  )

  printf "Downloading CCDB snapshot\nfrom: '%s'\n" "${CCDB_URL}"
  curl --silent "${curl_headers[@]}" "${CCDB_URL}" \
    --create-dirs --output "${SNAPSHOT_FILE}" \
    --write-out "  to: '%{filename_effective}' (%{size_download} bytes)\n"
}
generate_info() {
  local snapshot_file_info="${SNAPSHOT_FILE_CHECK%.json}.info"
  {
    printf "# Generated by '%s' on %s\n#\n" "$(realpath "$0")" "$(date +%F)"
    printf "# === ONLINE query ===\n"
    printf "# %s\n" "${CCDB_URL}"
    printf "# %23s %8s %23s\n" "$(ts_human_to_millis "${TS_LOWER}")" "->" "$(ts_human_to_millis "${TS_UPPER}")"
    printf "# %s %s %s\n#\n" "${TS_LOWER}" "->" "${TS_UPPER}"
    printf "# === SNAPSHOT result ===\n"
    printf "# %s\n" "${SNAPSHOT_FILE_CHECK#"${SNAPSHOT_BASE}/"}" # relative path
    printf "# %23s %8s %23s\n" "${TS_LOWER_CHECK}" "->" "${TS_UPPER_CHECK}"
    printf "# %s %s %s\n" "$(ts_millis_to_human "${TS_LOWER_CHECK}")" "->" "$(ts_millis_to_human "${TS_UPPER_CHECK}")"
  } > "${snapshot_file_info}"
  printf "Writing snapshot info\n  to: '%s'\n\n" "${snapshot_file_info}"
  cat "${snapshot_file_info}"
}

# ================================ OPTIONS =====================================
CCDB_HOST='alice-ccdb.cern.ch'
CCDB_PATH='GLO/Config/GRPLHCIF' # General Run Parameters from LHC InterFace data
# CCDB_PATH='RCT/Info/RunInformation' # Run Condition Table

# Lower/Upper timestamp, any format accepted by 'date --date=STRING'
TS_LOWER='2026-03-01'
TS_UPPER='2026-07-01'
# TS_LOWER="0"       # minimum timestamp, special case for '1970-01-01'
# TS_UPPER="$(date)" # maximum timestamp, current time

SNAPSHOT_BASE="${HOME}/ALICE-DATA/ccdb"
# ==============================================================================

DATE_FMT="+%F %T.%3N%:z" # 2026-07-15 21:47:52.718+02:00
# timestamp "human" format (ALICE use milliseconds resolution)
TS_LOWER="$(ts_human_format "${TS_LOWER}")" # only for uniform formatting
TS_UPPER="$(ts_human_format "${TS_UPPER}")" # only for uniform formatting
CCDB_URL="http://${CCDB_HOST}/browse/${CCDB_PATH}"
SNAPSHOT_FILE="${SNAPSHOT_BASE}/${CCDB_PATH}/snapshot.tmp.json"
curl_ccdb

TS_LOWER_CHECK="$(jq -r '.objects[-1].Created' "${SNAPSHOT_FILE}")"
TS_UPPER_CHECK="$(jq -r '.objects[0].Created' "${SNAPSHOT_FILE}")"
# uuid_time "$(jq -r '.objects[-1].id' "${SNAPSHOT_FILE}")"
# uuid_time "$(jq -r '.objects[0].id' "${SNAPSHOT_FILE}")"

SNAPSHOT_FILE_CHECK="${SNAPSHOT_FILE%.tmp.json}.${TS_LOWER_CHECK}-${TS_UPPER_CHECK}.json"
# /path/to/snapshot.tmp.json => /path/to/snapshot.LOWER-UPPER.json
mv "${SNAPSHOT_FILE}" "${SNAPSHOT_FILE_CHECK}" \
  && printf "Renaming snapshot file\n  to: '%s'\n" "${SNAPSHOT_FILE_CHECK}"
touch --date="@${TS_UPPER_CHECK:0:-3}" "${SNAPSHOT_FILE_CHECK}"

generate_info
